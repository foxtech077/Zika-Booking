interface CountryComboboxProps {
  label?: string;
  value: string;
  onChange: (value: string) => void;
  error?: string;
  className?: string;
}

export function CountryCombobox({ label, value, onChange, error, className }: CountryComboboxProps) {
  const [isOpen, setIsOpen] = useState(false);
  const [search, setSearch] = useState("");
  const containerRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const handleOutsideClick = (e: MouseEvent) => {
      if (containerRef.current && !containerRef.current.contains(e.target as Node)) {
        setIsOpen(false);
      }
    };
    if (isOpen) {
      document.addEventListener("mousedown", handleOutsideClick);
    }
    return () => document.removeEventListener("mousedown", handleOutsideClick);
  }, [isOpen]);

  const filteredCountries = useMemo(() => {
    const query = search.toLowerCase();
    return WORLD_COUNTRIES.filter(
      (c) => c.code.toLowerCase().includes(query) || c.name.toLowerCase().includes(query)
    );
  }, [search]);

  const selectedCountry = WORLD_COUNTRIES.find((c) => c.code === value);
  const displayValue = selectedCountry ? `${selectedCountry.name} (${selectedCountry.code})` : value;

  return (
    <div className={cn("w-full", className)} ref={containerRef}>
      {label && (
        <label className="block text-sm font-medium text-slate-700 mb-1.5">
          {label}
        </label>
      )}
      <div className="relative">
        <button
          type="button"
          onClick={() => setIsOpen(!isOpen)}
          className={cn(
            "w-full h-10 rounded-xl border bg-white px-3 text-sm text-left flex items-center justify-between",
            "transition-all duration-150 outline-none focus:ring-2 focus:ring-[#4c6a48]",
            error ? "border-red-500 focus:ring-red-500" : "border-slate-200 hover:border-slate-400",
            !selectedCountry && "text-slate-400"
          )}
        >
          <span className="truncate">{selectedCountry ? displayValue : "Select country..."}</span>
          <ChevronDown className="w-4 h-4 text-slate-400 shrink-0" />
        </button>

        {isOpen && (
          <div className="absolute z-50 w-full mt-1 bg-white border border-slate-200 rounded-xl shadow-lg overflow-hidden animate-in fade-in zoom-in-95 duration-100">
            <div className="p-2 border-b border-slate-200 flex items-center gap-2">
              <Search className="w-4 h-4 text-slate-400 shrink-0" />
              <input
                type="text"
                className="w-full bg-transparent text-sm outline-none placeholder:text-slate-400"
                placeholder="Search country..."
                value={search}
                onChange={(e) => setSearch(e.target.value)}
                autoFocus
              />
            </div>
            <ul className="max-h-60 overflow-y-auto p-1">
              {filteredCountries.length === 0 ? (
                <li className="p-3 text-center text-sm text-slate-500">No countries found.</li>
              ) : (
                filteredCountries.map((c) => (
                  <li
                    key={c.code}
                    className={cn(
                      "flex items-center justify-between px-3 py-2 text-sm rounded-lg cursor-pointer transition-colors",
                      value === c.code ? "bg-slate-50 text-slate-900 font-medium" : "hover:bg-slate-50 text-slate-700"
                    )}
                    onClick={() => {
                      onChange(c.code);
                      setIsOpen(false);
                      setSearch("");
                    }}
                  >
                    <span>{c.name} ({c.code})</span>
                    {value === c.code && <Check className="w-4 h-4 text-slate-900 shrink-0" />}
                  </li>
                ))
              )}
            </ul>
          </div>
        )}
      </div>
      {error && <p className="mt-1 text-xs text-red-500">{error}</p>}
    </div>
  );
}
